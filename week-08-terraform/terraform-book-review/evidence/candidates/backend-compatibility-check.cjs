const assert = require('node:assert/strict');
const {createRequire}=require('node:module');
const req=createRequire(require.resolve('sequelize'));
const uuid=req('uuid');
assert.equal(require('sequelize/package.json').version.split('.')[0],'6');
assert.match(uuid.v1(),/^[0-9a-f-]{36}$/);
assert.match(uuid.v4(),/^[0-9a-f-]{36}$/);
const Sequelize=require('sequelize');
const db=new Sequelize('test','test','synthetic',{dialect:'mysql',logging:false});
const Book=db.define('Book',{id:{type:Sequelize.UUID,defaultValue:Sequelize.UUIDV4,primaryKey:true},title:{type:Sequelize.STRING,allowNull:false}});
const book=Book.build({title:'offline dependency check'});
assert.equal(uuid.validate(book.id),true);
const q=db.getQueryInterface().queryGenerator.selectQuery('Books',{attributes:['id','title'],limit:5});
assert.match(q,/SELECT/);assert.match(q,/LIMIT 5/);
assert.equal(typeof require('mysql2').createConnection,'function');
const bcrypt=require('bcryptjs');assert.equal(bcrypt.compareSync('synthetic',bcrypt.hashSync('synthetic',4)),true);
const jwt=require('jsonwebtoken');assert.equal(jwt.verify(jwt.sign({sub:'test'},'synthetic-test-key',{algorithm:'HS256'}),'synthetic-test-key',{algorithms:['HS256']}).sub,'test');
const express=require('express');assert.equal(typeof express().use,'function');
console.log(JSON.stringify({result:'passed',node:process.version,platform:process.platform,arch:process.arch,checks:['Sequelize6 CommonJS uuid v1/v4 resolution','UUIDV4 model default','MySQL SELECT generation','mysql2 API load','bcrypt hash/compare','JWT HS256 sign/verify','Express API load'],network:'none',database_connection:false}));
